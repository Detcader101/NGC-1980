// merge the side/front and top traces into game/js/units/air/fa18trace.js (the F/A-18A station table's source)
//   node blueprint/fa18a/merge.mjs   (after trace3view.mjs on side-front.config.json and top.config.json)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const D = path.dirname(fileURLToPath(import.meta.url)), OUT = path.resolve(D, '../../../game/js/units/air/fa18trace.json');
const a = JSON.parse(fs.readFileSync(path.join(D, 'trace-side-front.json'), 'utf8')), b = JSON.parse(fs.readFileSync(path.join(D, 'trace-top.json'), 'utf8'));
const out = { source: { sideFront: a.source, top: b.source }, frame: a.frame, calibration: { side: a.calibration.side, top: b.calibration.top, front: a.calibration.front }, side: a.side, top: b.top, front: a.front };
fs.writeFileSync(OUT, JSON.stringify(out));
fs.writeFileSync(OUT.replace(/\.json$/, '.js'), '// generated by tools/blueprint/fa18a/merge.mjs from the traced NASA three-view (see fa18trace.json, docs/ngc1980/reference/fa18a)\nexport const FA18_TRACE = ' + JSON.stringify(out) + ';\n');
console.log('wrote', OUT, fs.statSync(OUT).size, 'bytes');
