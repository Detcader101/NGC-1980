// merge.mjs - build game/js/units/air/rotary/ch46trace.js (the CH-46E station table's source) from fig. 2-1 of
// NADC-81118-60: the side view traced by trace3view.mjs (side-top.config.json), and the top view's half-widths read by
// a column scan (the top view is crossed by blades, disc arcs and dimension lines, so the flood tracer leaks there):
// per column the outermost dark run inside the cabin band (+-1.35 m, or +-2.25 m over the sponsons) is the body edge;
// columns where a blade crosses the body (z -5.6..-4.6, 4.4..5.6) or the main gear's dashed outline shows (2.45..2.75)
// are left null and bridged by the sampler. Widths are taken to the outline's centre (half the ~8 px line off).
//   CHROME_PATH=... node blueprint/ch46e/merge.mjs   (after trace3view.mjs side-top.config.json)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { createRequire } from 'node:module';
const puppeteer = (await import(pathToFileURL(createRequire(process.cwd() + '/').resolve('puppeteer-core')).href)).default;
const D = path.dirname(fileURLToPath(import.meta.url)), OUT = path.resolve(D, '../../../game/js/units/air/rotary/ch46trace.json');
const cfg = JSON.parse(fs.readFileSync(path.join(D, 'side-top.config.json'), 'utf8')), a = JSON.parse(fs.readFileSync(path.join(D, 'trace-side-top.json'), 'utf8'));
const T = cfg.top, img = path.resolve(D, cfg.image);
const br = await puppeteer.launch({ executablePath: process.env.CHROME_PATH, args: ['--no-sandbox'] }); const pg = await br.newPage();
const top = await pg.evaluate(async (src, T) => {
  const im = new Image(); im.src = src; await im.decode(); const W = im.width, H = im.height, c = document.createElement('canvas'); c.width = W; c.height = H;
  const x = c.getContext('2d'); x.drawImage(im, 0, 0); const d = x.getImageData(0, 0, W, H).data, dk = (i, j) => Math.min(d[(j * W + i) * 4], d[(j * W + i) * 4 + 1], d[(j * W + i) * 4 + 2]) < 150;
  const out = [], LINE = 8;   // the drawing's outline is ~8 px thick at 6x
  for (let px = T.x0; px <= T.x1; px++) {
    const z = (px - T.xRef) / T.s + T.zRef, spon = z > 0.85 && z < 2.55, band = (spon ? 2.25 : 1.35) * T.s;
    let lo = null, hi = null;
    for (let j = Math.round(T.centrePx - band); j <= T.centrePx + band; j++) if (dk(px, j)) { if (lo === null) lo = j; hi = j; }
    const blade = (z > -5.6 && z < -4.6) || (z > 4.4 && z < 5.6) || (z > 2.45 && z < 2.75);   // (blades crossing; the main gear's dashed outline beside the sponson's end)
    out.push({ z: +z.toFixed(4), hw: lo === null || blade ? null : +(((hi - lo) / 2 - LINE / 2) / T.s).toFixed(4) });   // (to the line's centre, as the tracer does)
  }
  return out;
}, 'data:image/png;base64,' + fs.readFileSync(img).toString('base64'), T);
await br.close();
const out = { source: a.source, frame: a.frame, calibration: { side: a.calibration.side, top: T }, side: a.side, top };
fs.writeFileSync(OUT, JSON.stringify(out));
fs.writeFileSync(OUT.replace(/\.json$/, '.js'), '// generated by tools/blueprint/ch46e/merge.mjs from NADC-81118-60 fig. 2-1 (see ch46trace.json, docs/ngc1980/reference/ch46e)\nexport const CH46_TRACE = ' + JSON.stringify(out) + ';\n');
console.log('wrote', OUT, fs.statSync(OUT).size, 'bytes');
